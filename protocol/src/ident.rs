/// 是否为有效的遥测站分类码字符。
pub fn is_class_char(c: char) -> bool {
    CLASS_CODES.iter().any(|(ch, _)| *ch == c)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_lookups() {
        assert_eq!(by_name("Z").unwrap().lead, 0x39);
        assert_eq!(by_name("VT").unwrap().unit, "伏特");
        assert_eq!(by_lead(0x38).unwrap().name, "VT");
        assert_eq!(drz_name(0xF5), Some("DRZ1"));
        assert_eq!(drz_name(0xFC), Some("DRZ8"));
        assert!(drz_name(0xFD).is_none());
        assert!(is_class_char('H'));
        assert!(!is_class_char('X'));
        // 表无重复引导符
        let mut leads: Vec<u8> = IDENTS.iter().map(|d| d.lead).collect();
        leads.sort();
        leads.dedup();
        assert_eq!(leads.len(), IDENTS.len());
    }
}
