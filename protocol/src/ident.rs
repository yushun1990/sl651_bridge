/// 标识符定义 (附录C 表C.1)。
#[derive(Debug, Clone, Copy)]
pub struct IdentDef {
    /// 标识符引导符
    pub lead: u8,
    /// 标识符 ASCⅡ 码
    pub name: &'static str,
    /// 编码要素
    pub desc: &'static str,
    /// 量和单位
    pub unit: &'static str,
    /// N(D,d) 的 D (小数点外位数); 0 表示非数值型
    pub digits: u8,
    /// N(D,d) 的 d (小数位数)
    pub decimals: u8,
}

macro_rules! idents {
    ($( $lead:literal, $name:literal, $desc:literal, $unit:literal, $digits:literal, $dec:literal );* $(;)?) => {
        /// 附录C 标识符表 (不含结构性引导符 F0~FD)。
        pub static IDENTS: &[IdentDef] = &[
            $( IdentDef { lead: $lead, name: $name, desc: $desc, unit: $unit, digits: $digits, decimals: $dec } ),*
        ];
    };
}

