/// 按 ASCII 标识符名查表。
pub fn by_name(name: &str) -> Option<&'static IdentDef> {
    IDENTS.iter().find(|d| d.name == name)
}

/// 按引导符查表。
pub fn by_lead(lead: u8) -> Option<&'static IdentDef> {
    IDENTS.iter().find(|d| d.lead == lead)
}

/// DRZ1..DRZ8 引导符 -> 标识符名。
pub fn drz_name(lead: u8) -> Option<&'static str> {
    if (LEAD_DRZ1..=LEAD_DRZ8).contains(&lead) {
        let idx = lead - LEAD_DRZ1;
        Some(DRZ_NAMES[idx as usize])
    } else {
        None
    }
}

static DRZ_NAMES: [&str; 8] = ["DRZ1", "DRZ2", "DRZ3", "DRZ4", "DRZ5", "DRZ6", "DRZ7", "DRZ8"];

